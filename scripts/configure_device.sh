#!/usr/bin/env bash
# Generate firmware/main/secrets.h (git-ignored, mode 600) WITHOUT printing secrets.
#
#   scripts/configure_device.sh [--device-id dev-01] [--backend-url http://IP:8000] [--wifi-from FILE]
#
# Wi-Fi credentials are taken from (first found):
#   $UNS_WIFI_SSID / $UNS_WIFI_PASSWORD environment variables, or
#   --wifi-from FILE  (a C header defining WIFI_SSID and WIFI_PASSWORD, e.g. spotify_speaker/main/wifi_config.h)
# A new device token is provisioned in the backend database; any previous token for that id stops working.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEV_ID="dev-01"; URL=""; WIFI_FROM=""
while [ $# -gt 0 ]; do
  case "$1" in
    --device-id) DEV_ID="$2"; shift 2;;
    --backend-url) URL="$2"; shift 2;;
    --wifi-from) WIFI_FROM="$2"; shift 2;;
    *) echo "unknown option $1"; exit 2;;
  esac
done
if [ -z "$URL" ]; then
  IP=$(ipconfig getifaddr en0 2>/dev/null || true)
  [ -n "$IP" ] || { echo "Could not detect the Mac's LAN IP; pass --backend-url http://<ip>:8000"; exit 1; }
  URL="http://$IP:8000"
fi
case "$URL" in *localhost*|*127.0.0.1*) echo "Backend URL must be the Mac's LAN address, not localhost"; exit 1;; esac

TMP=$(mktemp); trap 'rm -f "$TMP"' EXIT
( cd "$ROOT/backend" && .venv/bin/python -m app.cli provision-device "$DEV_ID" --label "ESP32-S3 companion" --token-file "$TMP" >/dev/null )

UNS_DEVICE_ID="$DEV_ID" UNS_BACKEND_URL="$URL" WIFI_FROM="$WIFI_FROM" TOKEN_FILE="$TMP" OUT="$ROOT/firmware/main/secrets.h" \
"$ROOT/backend/.venv/bin/python" - <<'PY'
import os, re, sys
ssid, pw = os.environ.get("UNS_WIFI_SSID"), os.environ.get("UNS_WIFI_PASSWORD")
src = os.environ.get("WIFI_FROM")
if not ssid and src:
    text = open(src, encoding="utf-8").read()
    def grab(name):
        m = re.search(rf'#define\s+{name}\s+"((?:[^"\\]|\\.)*)"', text)
        return m.group(1).encode().decode("unicode_escape") if m else None
    ssid, pw = grab("WIFI_SSID"), grab("WIFI_PASSWORD")
if not ssid or pw is None:
    sys.exit("No Wi-Fi credentials: set UNS_WIFI_SSID/UNS_WIFI_PASSWORD or pass --wifi-from FILE")
def c(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
tok = open(os.environ["TOKEN_FILE"]).read().strip()
body = f"""// GENERATED by scripts/configure_device.sh - git-ignored, do not commit.
#pragma once
#define UNS_WIFI_SSID       {c(ssid)}
#define UNS_WIFI_PASSWORD   {c(pw)}
#define UNS_BACKEND_URL     {c(os.environ['UNS_BACKEND_URL'])}
#define UNS_DEVICE_ID       {c(os.environ['UNS_DEVICE_ID'])}
#define UNS_DEVICE_TOKEN    {c(tok)}
"""
out = os.environ["OUT"]
fd = os.open(out, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w") as f:
    f.write(body)
os.chmod(out, 0o600)
print(f"Wrote {out} (Wi-Fi network name: {len(ssid)} chars, password: {'set' if pw else 'empty'}; values not shown)")
PY
echo "Device id: $DEV_ID   Backend URL baked into firmware: $URL"
echo "Next: scripts/flash.sh"
